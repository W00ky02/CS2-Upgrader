function getSkinImage(name) {
    const slug = name
        .toLowerCase()
        .replace(/™/g, "")
        .replace(/\|/g, "")
        .replace(/'/g, "")
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-+|-+$/g, "");

    return `https://csgoskins.gg/items/${slug}`;
}


function getSkinModel(name) {
    const lower = name.toLowerCase();

    if (
        lower.includes("knife") ||
        lower.includes("karambit") ||
        lower.includes("bayonet") ||
        lower.includes("talon") ||
        lower.includes("butterfly") ||
        lower.includes("bowie") ||
        lower.includes("gut") ||
        lower.includes("skeleton") ||
        lower.includes("navaja") ||
        lower.includes("nomad") ||
        lower.includes("paracord") ||
        lower.includes("stiletto") ||
        lower.includes("survival") ||
        lower.includes("ursus") ||
        lower.includes("kukri")
    ) return "knife";

    if (
        lower.includes("awp") ||
        lower.includes("ssg") ||
        lower.includes("scar-20") ||
        lower.includes("g3sg1")
    ) return "sniper";

    if (
        lower.includes("glock") ||
        lower.includes("usp") ||
        lower.includes("p250") ||
        lower.includes("deagle") ||
        lower.includes("desert") ||
        lower.includes("five-seven") ||
        lower.includes("tec-9") ||
        lower.includes("cz75") ||
        lower.includes("p2000") ||
        lower.includes("dual berettas")
    ) return "pistol";

    if (
        lower.includes("mp7") ||
        lower.includes("mp9") ||
        lower.includes("mac-10") ||
        lower.includes("p90") ||
        lower.includes("ump-45") ||
        lower.includes("pp-bizon")
    ) return "smg";

    if (
        lower.includes("nova") ||
        lower.includes("mag-7") ||
        lower.includes("xm1014") ||
        lower.includes("sawed-off")
    ) return "shotgun";

    if (
        lower.includes("negev") ||
        lower.includes("m249")
    ) return "heavy";

    return "rifle";
}

