function skin(name, price, c1, c2) {
    const image = getSkinImage(name);

    if (!image) {
        console.warn("Skin ohne vorhandenes PNG ignoriert:", name);
        return null;
    }

    const finishColors = getFinishColors(name, c1, c2);
    c1 = finishColors[0];
    c2 = finishColors[1];

    return {
        name,
        price,
        color: `linear-gradient(135deg,${c1},${c2})`,
        main: c1,
        dark: c2,
        model: getSkinModel(name),
        image
    };
}

function cleanSkins(items) {
    const seen = new Set();

    return items.filter(item => {
        if (!item || seen.has(item.name)) return false;
        seen.add(item.name);
        return true;
    });
}

